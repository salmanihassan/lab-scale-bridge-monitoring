%% REPS ME-2 Digital Twin Baseline Visualization
%
% Reads:
%   9_4_26/ME2_master_features.csv
%
% Creates:
%   9_4_26/plots/
%
% Run AFTER:
%   clean_ME2_data.m
%
% Purpose:
%   Visualize the cleaned physical baseline dataset before digital-twin
%   training. These plots are intended to verify repeatability, physical
%   trends, load-position effects, vibration response, and temperature
%   behavior.
%
% Author: Blayne Montaque
% Fall 2026

clear;
clc;
close all;

%% ================================================================
% PATHS
% ================================================================

dataDir = fullfile(pwd, '9_4_26');

featureFile = fullfile( ...
    dataDir, ...
    'ME2_master_features.csv');

plotDir = fullfile( ...
    dataDir, ...
    'plots');

if ~isfile(featureFile)
    error(['Could not find ME2_master_features.csv.' newline ...
        'Run clean_ME2_data.m first.']);
end

if ~isfolder(plotDir)
    mkdir(plotDir);
end

%% ================================================================
% LOAD MASTER FEATURE TABLE
% ================================================================

T = readtable(featureFile);

fprintf('\n============================================================\n');
fprintf(' REPS ME-2 BASELINE VISUALIZATION\n');
fprintf('============================================================\n');

fprintf('Runs loaded: %d\n', height(T));
fprintf('Feature table: %s\n\n', featureFile);

%% ================================================================
% BASIC DERIVED VARIABLES
% ================================================================

% Combined load-cell response.
T.lc_total_median = ...
    T.lc_left_median + ...
    T.lc_right_median;

T.lc_difference_median = ...
    T.lc_left_median - ...
    T.lc_right_median;

% Normalized left/right load distribution.
T.lc_left_fraction = ...
    T.lc_left_median ./ ...
    T.lc_total_median;

T.lc_right_fraction = ...
    T.lc_right_median ./ ...
    T.lc_total_median;

%% ================================================================
% IDENTIFY TEST GROUPS
% ================================================================

staticMask = ...
    T.vibration_pwm == 0 & ...
    isfinite(T.load_kg) & ...
    T.load_kg > 0;

noLoadMask = ...
    T.load_kg == 0;

vibrationMask = ...
    T.vibration_pwm > 0;

frequencySweepMask = ...
    vibrationMask & ...
    contains(string(T.frequency_source),'filename');

%% ================================================================
% PLOT 1
% LOAD-CELL RESPONSE VS APPLIED LOAD
% ================================================================

figure(1);
clf;

staticT = T(staticMask,:);

positions = [0.25 0.50 0.75];

for p = 1:length(positions)

    xPos = positions(p);

    mask = ...
        abs(staticT.load_position_norm - xPos) < 0.001;

    subset = staticT(mask,:);

    if isempty(subset)
        continue
    end

    plot( ...
        subset.load_kg, ...
        subset.lc_left_median, ...
        'o-', ...
        'LineWidth',1.5, ...
        'DisplayName', ...
        sprintf('Left LC, x/L = %.2f',xPos));

    hold on;

    plot( ...
        subset.load_kg, ...
        subset.lc_right_median, ...
        's--', ...
        'LineWidth',1.5, ...
        'DisplayName', ...
        sprintf('Right LC, x/L = %.2f',xPos));

end

grid on;
box on;

xlabel('Applied Load [kg]');
ylabel('Median Load-Cell Raw Output');

title( ...
    'Load-Cell Response vs Applied Load');

legend( ...
    'Location','best');

exportgraphics( ...
    gcf, ...
    fullfile(plotDir, ...
    '01_loadcell_response_vs_load.png'), ...
    'Resolution',300);

%% ================================================================
% PLOT 2
% LEFT/RIGHT RESPONSE VS LOAD POSITION
% ================================================================

figure(2);
clf;

loadLevels = unique( ...
    staticT.load_kg);

loadLevels = loadLevels( ...
    isfinite(loadLevels));

for k = 1:length(loadLevels)

    L = loadLevels(k);

    mask = ...
        abs(staticT.load_kg - L) < 1e-6;

    subset = staticT(mask,:);

    % Average repeated runs at each position.
    [positionsUnique,~,groupIndex] = ...
        unique(subset.load_position_norm);

    leftMean = ...
        accumarray( ...
        groupIndex, ...
        subset.lc_left_median, ...
        [], ...
        @mean);

    rightMean = ...
        accumarray( ...
        groupIndex, ...
        subset.lc_right_median, ...
        [], ...
        @mean);

    plot( ...
        positionsUnique, ...
        leftMean, ...
        'o-', ...
        'LineWidth',1.5, ...
        'DisplayName', ...
        sprintf('Left LC, %.2f kg',L));

    hold on;

    plot( ...
        positionsUnique, ...
        rightMean, ...
        's--', ...
        'LineWidth',1.5, ...
        'DisplayName', ...
        sprintf('Right LC, %.2f kg',L));

end

grid on;
box on;

xlabel('Normalized Load Position, x/L');
ylabel('Median Load-Cell Raw Output');

xticks([0.25 0.50 0.75]);
xticklabels({'Left','Center','Right'});

title( ...
    'Load Distribution vs Load Position');

legend( ...
    'Location','best');

exportgraphics( ...
    gcf, ...
    fullfile(plotDir, ...
    '02_load_distribution_vs_position.png'), ...
    'Resolution',300);

%% ================================================================
% PLOT 3
% NORMALIZED LOAD DISTRIBUTION
% ================================================================

figure(3);
clf;

for k = 1:length(loadLevels)

    L = loadLevels(k);

    mask = ...
        abs(staticT.load_kg - L) < 1e-6;

    subset = staticT(mask,:);

    [positionsUnique,~,groupIndex] = ...
        unique(subset.load_position_norm);

    leftFraction = ...
        accumarray( ...
        groupIndex, ...
        subset.lc_left_fraction, ...
        [], ...
        @mean);

    plot( ...
        positionsUnique, ...
        leftFraction, ...
        'o-', ...
        'LineWidth',1.5, ...
        'DisplayName', ...
        sprintf('%.2f kg',L));

    hold on;

end

% Ideal simply-supported reaction fraction:
%
% R_left / P = 1 - x/L

xIdeal = linspace(0,1,100);

plot( ...
    xIdeal, ...
    1-xIdeal, ...
    'k--', ...
    'LineWidth',1.5, ...
    'DisplayName','Ideal beam reaction trend');

grid on;
box on;

xlabel('Normalized Load Position, x/L');
ylabel('Normalized Left Load-Cell Fraction');

xlim([0 1]);
ylim([0 1]);

title( ...
    'Measured Load Distribution vs Beam-Statics Trend');

legend( ...
    'Location','best');

exportgraphics( ...
    gcf, ...
    fullfile(plotDir, ...
    '03_normalized_load_distribution.png'), ...
    'Resolution',300);

%% ================================================================
% PLOT 4
% TOTAL LOAD-CELL RESPONSE VS APPLIED LOAD
% ================================================================

figure(4);
clf;

scatter( ...
    staticT.load_kg, ...
    staticT.lc_total_median, ...
    55, ...
    staticT.load_position_norm, ...
    'filled');

grid on;
box on;

xlabel('Applied Load [kg]');
ylabel('LC_L + LC_R [raw counts]');

title( ...
    'Combined Load-Cell Response vs Applied Load');

cb = colorbar;
cb.Label.String = ...
    'Normalized Load Position';

exportgraphics( ...
    gcf, ...
    fullfile(plotDir, ...
    '04_total_loadcell_response_vs_load.png'), ...
    'Resolution',300);

%% ================================================================
% PLOT 5
% LOAD-CELL REPEATABILITY
% ================================================================

figure(5);
clf;

conditions = ...
    findgroups( ...
    staticT.load_kg, ...
    staticT.load_position_norm);

groupLoad = ...
    splitapply( ...
    @mean, ...
    staticT.load_kg, ...
    conditions);

groupPosition = ...
    splitapply( ...
    @mean, ...
    staticT.load_position_norm, ...
    conditions);

leftMean = ...
    splitapply( ...
    @mean, ...
    staticT.lc_left_median, ...
    conditions);

leftStd = ...
    splitapply( ...
    @std, ...
    staticT.lc_left_median, ...
    conditions);

rightMean = ...
    splitapply( ...
    @mean, ...
    staticT.lc_right_median, ...
    conditions);

rightStd = ...
    splitapply( ...
    @std, ...
    staticT.lc_right_median, ...
    conditions);

conditionLabels = strings(length(groupLoad),1);

for i = 1:length(groupLoad)

    if abs(groupPosition(i)-0.25) < 0.01
        posString = "L";
    elseif abs(groupPosition(i)-0.50) < 0.01
        posString = "C";
    elseif abs(groupPosition(i)-0.75) < 0.01
        posString = "R";
    else
        posString = "?";
    end

    conditionLabels(i) = ...
        sprintf('%.2f kg-%s', ...
        groupLoad(i), ...
        posString);
end

x = 1:length(groupLoad);

errorbar( ...
    x-0.08, ...
    leftMean, ...
    leftStd, ...
    'o', ...
    'LineWidth',1.5);

hold on;

errorbar( ...
    x+0.08, ...
    rightMean, ...
    rightStd, ...
    's', ...
    'LineWidth',1.5);

grid on;
box on;

xticks(x);
xticklabels(conditionLabels);
xtickangle(45);

ylabel('Median Load-Cell Raw Output');

title( ...
    'Repeatability Across Static Load Conditions');

legend( ...
    {'Left LC','Right LC'}, ...
    'Location','best');

exportgraphics( ...
    gcf, ...
    fullfile(plotDir, ...
    '05_static_repeatability.png'), ...
    'Resolution',300);

%% ================================================================
% PLOT 6
% VIBRATION RMS VS PWM
% ================================================================

figure(6);
clf;

vibT = T( ...
    noLoadMask & ...
    T.vibration_pwm >= 0 & ...
    ~contains(string(T.frequency_source),'filename'),:);

if ~isempty(vibT)

    pwmLevels = ...
        unique(vibT.vibration_pwm);

    meanRMS = nan(size(pwmLevels));
    stdRMS = nan(size(pwmLevels));

    for i = 1:length(pwmLevels)

        mask = ...
            vibT.vibration_pwm == ...
            pwmLevels(i);

        meanRMS(i) = ...
            mean(vibT.accel_rms_g(mask));

        stdRMS(i) = ...
            std(vibT.accel_rms_g(mask));

    end

    errorbar( ...
        pwmLevels, ...
        meanRMS, ...
        stdRMS, ...
        'o-', ...
        'LineWidth',1.5);

    grid on;
    box on;

    xlabel('Vibration Motor Command [PWM]');
    ylabel('Acceleration RMS [g]');

    title( ...
        'No-Load Dynamic Response vs Vibration Amplitude');

else

    text( ...
        0.5,0.5, ...
        'No amplitude-sweep data identified', ...
        'HorizontalAlignment','center');

    axis off;

end

exportgraphics( ...
    gcf, ...
    fullfile(plotDir, ...
    '06_acceleration_rms_vs_pwm.png'), ...
    'Resolution',300);

%% ================================================================
% PLOT 7
% MEASURED DOMINANT FREQUENCY VS COMMANDED FREQUENCY
% ================================================================

figure(7);
clf;

freqT = T(frequencySweepMask,:);

if ~isempty(freqT)

    scatter( ...
        freqT.commanded_frequency_Hz, ...
        freqT.dominant_frequency_Hz, ...
        65, ...
        'filled');

    hold on;

    minF = min( ...
        freqT.commanded_frequency_Hz);

    maxF = max( ...
        freqT.commanded_frequency_Hz);

    plot( ...
        [minF maxF], ...
        [minF maxF], ...
        'k--', ...
        'LineWidth',1.5);

    grid on;
    box on;

    xlabel('Commanded Frequency [Hz]');
    ylabel('Measured Dominant Frequency [Hz]');

    title( ...
        'Commanded vs Measured Vibration Frequency');

    legend( ...
        {'Measured response','Ideal f_{dom}=f_{cmd}'}, ...
        'Location','best');

else

    text( ...
        0.5,0.5, ...
        'No frequency-sweep data identified', ...
        'HorizontalAlignment','center');

    axis off;

end

exportgraphics( ...
    gcf, ...
    fullfile(plotDir, ...
    '07_commanded_vs_dominant_frequency.png'), ...
    'Resolution',300);

%% ================================================================
% PLOT 8
% FFT PEAK MAGNITUDE VS EXCITATION FREQUENCY
% ================================================================

figure(8);
clf;

if ~isempty(freqT)

    commandedFreqs = ...
        unique(freqT.commanded_frequency_Hz);

    fftMean = nan(size(commandedFreqs));
    fftStd = nan(size(commandedFreqs));

    for i = 1:length(commandedFreqs)

        mask = ...
            freqT.commanded_frequency_Hz == ...
            commandedFreqs(i);

        fftMean(i) = ...
            mean(freqT.fft_peak_magnitude(mask));

        fftStd(i) = ...
            std(freqT.fft_peak_magnitude(mask));

    end

    errorbar( ...
        commandedFreqs, ...
        fftMean, ...
        fftStd, ...
        'o-', ...
        'LineWidth',1.5);

    grid on;
    box on;

    xlabel('Commanded Excitation Frequency [Hz]');
    ylabel('FFT Peak Magnitude');

    title( ...
        'Frequency Response of Bridge');

else

    text( ...
        0.5,0.5, ...
        'No frequency-sweep data identified', ...
        'HorizontalAlignment','center');

    axis off;

end

exportgraphics( ...
    gcf, ...
    fullfile(plotDir, ...
    '08_fft_peak_vs_excitation_frequency.png'), ...
    'Resolution',300);

%% ================================================================
% PLOT 9
